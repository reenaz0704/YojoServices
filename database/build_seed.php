<?php
/**
 * Generates database/seed.sql from the PHP content files in database/data.
 * Usage:  php database/build_seed.php
 * The generated seed.sql can be imported with phpMyAdmin or the mysql CLI after schema.sql.
 */
if (PHP_SAPI !== 'cli') { exit("CLI only\n"); }

$svc = require __DIR__ . '/data/services.php';
$c   = require __DIR__ . '/data/content.php';

function q($v): string
{
    if ($v === null) { return 'NULL'; }
    if (is_int($v) || is_float($v)) { return (string) $v; }
    return "'" . str_replace(["\\", "'", "\r", "\n", "\0"], ["\\\\", "\\'", "\\r", "\\n", "\\0"], (string) $v) . "'";
}
function row(array $vals): string { return '(' . implode(',', array_map('q', $vals)) . ')'; }
function ins(string $table, array $cols, array $rows): string
{
    if (!$rows) { return ''; }
    return "INSERT INTO `$table` (`" . implode('`,`', $cols) . "`) VALUES\n" . implode(",\n", array_map('row', $rows)) . ";\n\n";
}

$out = "-- Generated by database/build_seed.php on " . date('Y-m-d H:i') . "\n-- Import AFTER schema.sql\nSET NAMES utf8mb4;\nSET FOREIGN_KEY_CHECKS = 0;\n\n";

// Roles & default administrator (CHANGE THE PASSWORD AFTER FIRST LOGIN)
$out .= ins('roles', ['id', 'slug', 'name', 'level'], [[1, 'viewer', 'Viewer', 1], [2, 'editor', 'Content Editor', 2], [3, 'admin', 'Administrator', 3], [4, 'super_admin', 'Super Administrator', 4]]);
$out .= ins('users', ['id', 'role_id', 'name', 'email', 'password_hash', 'designation'], [
    [1, 4, 'Site Administrator', 'admin@yojosolutions.com', password_hash('ChangeMe@2026', PASSWORD_DEFAULT), 'Administrator'],
]);

$i = 0;
$out .= ins('settings', ['setting_key', 'setting_value', 'setting_group', 'label', 'input_type', 'sort_order'],
    array_map(function ($s) use (&$i) { return [$s[0], $s[1], $s[2], $s[3], $s[4], ++$i]; }, $c['settings']));

$out .= ins('pages', ['slug', 'title', 'content'], $c['pages']);

// Service categories & services
$catRows = []; $catIds = [];
foreach ($svc['categories'] as $n => $cat) {
    $catIds[$cat['slug']] = $n + 1;
    $catRows[] = [$n + 1, $cat['slug'], $cat['name'], $cat['tagline'], $cat['summary'], $cat['description'], $cat['engagement_note'], $cat['page_type'], $cat['icon'], $n + 1];
}
$out .= ins('service_categories', ['id', 'slug', 'name', 'tagline', 'summary', 'description', 'engagement_note', 'page_type', 'icon', 'sort_order'], $catRows);

$serviceRows = []; $faqRows = []; $serviceIds = []; $id = 0;
foreach ($svc['services'] as $catSlug => $list) {
    $d = $svc['defaults'][$catSlug];
    foreach ($list as $sort => $s) {
        list($slug, $title, $menu, $icon, $eng, $summary, $intro, $meaning, $why, $req) = $s;
        $extra = $s[10] ?? [];
        $id++;
        $serviceIds[$slug] = $id;
        $requirements = implode("\n", $req);
        $security = null;
        if (($extra['security_areas'] ?? null) === 'requirements') {
            $security = $requirements;
            $requirements = null;
        }
        $serviceRows[] = [
            $id, $catIds[$catSlug], $slug, $title, $menu, $eng, $icon, $summary, $intro, $meaning, $why, $requirements,
            $d['methodology'], $extra['scope'] ?? ($d['scope'] ?? null), $security, $d['deliverables'],
            $d['reporting'] ?? null, $d['remediation'] ?? null, $d['benefits'],
            $title . ' | Yojo Solutions', mb_substr($summary, 0, 300), $sort < 2 ? 1 : 0, $sort + 1,
        ];
        foreach ($d['faqs'] as $k => $f) {
            $faqRows[] = [$id, $f[0], $f[1], $k + 1];
        }
        // One service-specific FAQ
        $faqRows[] = [$id, 'How do we get started with ' . $title . '?', 'Book a short consultation. We will discuss your objectives, systems in scope and timelines, then share a tailored proposal with a clear scope, deliverables and fees.', 10];
    }
}
$out .= ins('services', ['id', 'category_id', 'slug', 'title', 'menu_group', 'engagement_type', 'icon', 'summary', 'intro', 'meaning', 'why_needed', 'requirements', 'methodology', 'scope', 'security_areas', 'deliverables', 'reporting', 'remediation', 'benefits', 'meta_title', 'meta_description', 'is_featured', 'sort_order'], $serviceRows);
$out .= ins('service_faqs', ['service_id', 'question', 'answer', 'sort_order'], $faqRows);

// Industries
$indRows = []; $pivot = []; $indIds = [];
foreach ($c['industries'] as $n => $ind) {
    list($slug, $name, $icon, $summary, $overview, $risks, $comp, $chal, $outc, $rec) = $ind;
    $indIds[$slug] = $n + 1;
    $indRows[] = [$n + 1, $slug, $name, $icon, $summary, $overview, implode("\n", $risks), implode("\n", $comp), implode("\n", $chal), implode("\n", $outc), $n + 1];
    foreach ($rec as $r) {
        if (!isset($serviceIds[$r])) { fwrite(STDERR, "Unknown service $r\n"); exit(1); }
        $pivot[] = [$n + 1, $serviceIds[$r]];
    }
}
$out .= ins('industries', ['id', 'slug', 'name', 'icon', 'summary', 'overview', 'risks', 'compliance', 'challenges', 'outcomes', 'sort_order'], $indRows);
$out .= ins('industry_service', ['industry_id', 'service_id'], $pivot);

$out .= ins('faqs', ['question', 'answer', 'topic', 'sort_order'], array_map(function ($f, $k) { return [$f[0], $f[1], $f[2], $k + 1]; }, $c['faqs'], array_keys($c['faqs'])));

$out .= ins('stats', ['label', 'value', 'suffix', 'description', 'is_verified', 'is_published', 'sort_order'],
    array_map(function ($s, $k) { return array_merge($s, [$k + 1]); }, $c['stats'], array_keys($c['stats'])));

$out .= ins('trust_items', ['type', 'name', 'note', 'is_verified', 'is_published', 'sort_order'],
    array_map(function ($t, $k) { return [$t[0], $t[1], $t[2], $t[3], $t[3], $k + 1]; }, $c['trust'], array_keys($c['trust'])));

$out .= ins('testimonials', ['client_name', 'designation', 'company', 'content', 'is_verified', 'is_published', 'sort_order'],
    array_map(function ($t, $k) { return [$t[0], $t[1], $t[2], $t[3], 0, 1, $k + 1]; }, $c['testimonials'], array_keys($c['testimonials'])));

$out .= ins('case_studies', ['slug', 'industry_id', 'title', 'client_label', 'challenge', 'assessment', 'improvements', 'remediation', 'outcome', 'is_authorized', 'is_published', 'sort_order'],
    array_map(function ($cs, $k) use ($indIds) { return [$cs[0], $indIds[$cs[1]], $cs[2], $cs[3], $cs[4], $cs[5], $cs[6], $cs[7], $cs[8], 0, 1, $k + 1]; }, $c['caseStudies'], array_keys($c['caseStudies'])));

// Blog
$pcIds = [];
$out .= ins('post_categories', ['id', 'slug', 'name', 'description', 'sort_order'], array_map(function ($pc, $k) use (&$pcIds) {
    $pcIds[$pc[0]] = $k + 1; return [$k + 1, $pc[0], $pc[1], $pc[2], $k + 1];
}, $c['postCategories'], array_keys($c['postCategories'])));

$postRows = []; $tagIds = []; $tagRows = []; $ptRows = [];
foreach ($c['posts'] as $n => $p) {
    list($slug, $cat, $title, $excerpt, $content, $tags) = $p;
    $words = str_word_count(strip_tags($content));
    $postRows[] = [$n + 1, $pcIds[$cat], 1, $slug, $title, $excerpt, $content, max(2, (int) ceil($words / 200)), $title, $excerpt, 'published', date('Y-m-d H:i:s', strtotime('-' . (($n + 1) * 9) . ' days'))];
    foreach ($tags as $t) {
        $ts = strtolower(trim(preg_replace('/[^A-Za-z0-9]+/', '-', $t), '-'));
        if (!isset($tagIds[$ts])) { $tagIds[$ts] = count($tagIds) + 1; $tagRows[] = [$tagIds[$ts], $ts, $t]; }
        $ptRows[] = [$n + 1, $tagIds[$ts]];
    }
}
$out .= ins('posts', ['id', 'category_id', 'author_id', 'slug', 'title', 'excerpt', 'content', 'reading_minutes', 'meta_title', 'meta_description', 'status', 'published_at'], $postRows);
$out .= ins('tags', ['id', 'slug', 'name'], $tagRows);
$out .= ins('post_tag', ['post_id', 'tag_id'], $ptRows);

$out .= "SET FOREIGN_KEY_CHECKS = 1;\n";
file_put_contents(__DIR__ . '/seed.sql', $out);
echo "seed.sql written: " . count($serviceRows) . " services, " . count($indRows) . " industries, " . count($postRows) . " posts\n";
